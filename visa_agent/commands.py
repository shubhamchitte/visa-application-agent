def _summary(res) -> str:
    p = res.plan
    return (f"  outcome={res.write_outcome} planned_status={p.status if p else None} patch={len(p.field_patch) if p else 0} fields "
            f"flags={res.flags}\n  issues: " + ("; ".join(f"{i.kind.value}:{i.field}" for i in res.issues) or "none"))


def demo(a) -> int:
    prov = os.getenv("LLM_PROVIDER") or "replay"
    rec = getattr(a, "record", False)
    if rec:
        prov = "replay"  # recording is always offline
    lines, rows = [], []
    out = DOCS / "demo_output"
    with tempfile.TemporaryDirectory() as tmp:
        for entry in DEMO:
            name, dry = entry.split("+")[0], entry.endswith("+dry")
            d = (REALISTIC if name[0] == "R" else CASES) / name
            exp = json.loads((d / "expected.json").read_text())
            recorded = (REPLAY_DIR / f"{Path(exp['packet']).name}.json").exists()
            use = prov if prov != "replay" or (name not in FAKE_ONLY and recorded) else "fake"
            no_ocr = exp.get("ocr_required") and ingest.ocr_backend() != "rapidocr"  # recorded on RapidOCR text
            if exp.get("realistic") and (not recorded or no_ocr):  # no scripted output exists for real-layout docs
                why = "needs RapidOCR: `make setup-ocr`" if no_ocr else "not recorded"
                text = f"\n=== {exp['scenario']:>2} {exp['title']}  (skipped: {why}) ==="
                print(text)
                lines.append(text)
                continue
            exp, res, llm = run_case(d, lambda c, d, r: make_llm(c, d, r, provider=use), Path(tmp), dry_run=dry)
            text = f"\n=== {exp['scenario']:>2} {exp['title']}{' [dry-run]' if dry else ''}  (provider={use}{':' + getattr(llm, 'model', '') if use == 'replay' else ''}) ===\n{_summary(res)}"
            if dry and res.plan:
                text += "\n  CRM diff: " + json.dumps(res.plan.field_patch)
            print(text)
            lines.append(text)
            if rec:
                slug = entry.replace("+", "_")
                p, r = res.plan, res.record_after or {}
                writes = sum(a["tool"] == "crm.update" and a["outcome"] == "OK" for a in res.audit)
                status = r.get("status") if res.write_outcome == "WRITTEN" else (f"{p.status} planned, not applied" if p else "-")
                head = (f"<!-- generated by `make demo-record`; do not edit -->\n**Scenario {exp['scenario']}: {exp['title']}**"
                        f"{' (dry run)' if dry else ''}. Provider: {use}.\n\n")
                out.mkdir(parents=True, exist_ok=True)
                (out / f"{slug}.md").write_text(head + to_markdown(res))
                (out / f"{slug}.json").write_text(to_json(res) + "\n")
                rows.append(f"| [{slug}]({slug}.md) | {exp['title']}{' (dry run)' if dry else ''} | {res.write_outcome} / {status} | {writes} |")
    if rec:
        (out / "TRANSCRIPT.md").write_text("# Demo console transcript\n\nOutput of `make demo-record` (replay provider, no network).\n\n```text"
                                          + "\n".join(lines) + "\n```\n")
        (out / "README.md").write_text(
            "# Demo output\n\nCommitted, deterministic output of `make demo-record` (replay provider, no network, frozen clock). "
            "Open a case to see extracted fields with quotes, issues, checklist, the CRM plan, final status and the tool-call log. "
            "Full console output: [TRANSCRIPT.md](TRANSCRIPT.md).\n\n| case | what it shows | final outcome / status | CRM writes |\n|---|---|---|---|\n"
            + "\n".join(rows) + "\n")
    return 0


def case(a) -> int:
    """One case with its golden fault plan and scripted LLM output (realistic: the replayed recording); prints the report.
    Works for the fault cases 07-13, which reuse case01's packet and so cannot be shown with `run`."""
    name = Path(a.name).name
    hits = [d for root in (CASES, REALISTIC) for d in sorted(root.glob(name + "*")) if (d / "expected.json").exists()]
    if not hits:
        print(f"no case matches {name!r}")
        return 2
    with tempfile.TemporaryDirectory() as tmp:
        prov = lambda c, d, r: make_llm(c, d, r, provider="replay" if d.parent == REALISTIC else "fake")
        _, res, _ = run_case(hits[0], prov, Path(tmp), dry_run=a.dry_run)
    print(to_markdown(res))  # exit 0 even on WRITE_FAILED: cases 11a/11b fail the write on purpose
    return 0


class _Tap:
    """Wraps a client and keeps the raw proposals, so hallucinations are counted before verify drops them."""
    def __init__(self, inner, pause: float = 0):
        self.pause, self.inner, self.name, self.model, self.raw = pause, inner, inner.name, getattr(inner, "model", inner.name), {}

    def extract(self, doc_id, prompt, schema):
        time.sleep(self.pause)  # free-tier pacing for --live
        out = self.raw[doc_id] = self.inner.extract(doc_id, prompt, schema)
        return out


SECTIONS = {"clean": "Clean generated set", "realistic": "Realistic set (real-layout form, dense multi-page docs, scans)"}


def _truth(case_dir: Path) -> dict:
    """Per-doc truth; name parts (extracted fields) are split off the printed full_name when the file lacks them."""
    t = json.loads((case_dir / "truth.json").read_text())
    given = t["person"]["given_names"]
    for d in t["documents"].values():
        if "full_name" in d and "surname" not in d:
            d.update(given_names=given, surname=d["full_name"][len(given) + 1:])
    return t["documents"]


def _quote_rate(dirs: list[Path]) -> str:
    """Verbatim-quote rate and call count computed from the recording files (raw responses vs the PDF text)."""
    from . import verify
    from .cases import packet_dir
    ok = n = calls = 0
    for d in dirs:
        exp = json.loads((d / "expected.json").read_text())
        saved = json.loads((REPLAY_DIR / f"{Path(exp['packet']).name}.json").read_text())
        pages = {x["doc_id"]: " ".join(verify.normalize(p["text"]) for p in x["pages"]) for x in ingest.ingest(packet_dir(d, exp), exp.get("ocr"))}
        for e in saved["entries"].values():
            calls += bool(e.get("request_id"))
            for f in ((e["response"].get("fields")) or {}).values():
                if f.get("evidence_quote"):
                    n += 1
                    ok += verify.normalize(f["evidence_quote"]) in pages.get(e["doc_id"], "")
    return (f"Run timestamp (UTC): {datetime.now(timezone.utc):%Y-%m-%d %H:%M:%S}  \nRecorded calls with a provider request id: {calls}  \n"
            f"Verbatim-quote rate, computed from mock_data/replay/*.json vs PDF text: {ok}/{n} ({ok / max(n, 1):.0%})\n")


def _case_dirs(which: str, only: list[str] | None) -> list[Path]:
    if which == "realistic":
        dirs = sorted(p for p in REALISTIC.iterdir() if (p / "expected.json").exists())
    else:  # one run per distinct packet
        dirs = sorted(p for p in CASES.iterdir() if (p / "truth.json").exists() and (p / "fake_llm.json").exists()
                      and json.loads((p / "expected.json").read_text())["packet"] == p.name)
    return [d for d in dirs if not only or any(d.name.startswith(o) for o in only)]


def eval(a) -> int:  # noqa: A001 (CLI verb)
    which, only = getattr(a, "set", None) or "clean", getattr(a, "only", None)
    prov = (os.getenv("LLM_PROVIDER") or "groq") if a.live else ("fake" if which == "clean" else "replay")
    stats: dict[str, list[int]] = {}  # field -> [correct, total]
    halluc, model, prop, dirs, notes = [], prov, [0, 0], [], []  # prop: [proposals with a value, of which survived verify]
    with tempfile.TemporaryDirectory() as tmp:
        for d in _case_dirs(which, only):
            exp = json.loads((d / "expected.json").read_text())
            if prov == "replay" and not (REPLAY_DIR / f"{Path(exp['packet']).name}.json").exists():
                notes.append(f"{d.name}: not recorded, skipped")
                continue
            if exp.get("ocr_required") and ingest.ocr_backend() != "rapidocr":
                notes.append(f"{d.name}: needs RapidOCR (`make setup-ocr`), skipped")
                continue
            tap = {}
            def mk(c, cd, r, tap=tap):
                live = a.live and prov not in ("replay", "groq")  # groq paces itself by tokens
                tap["t"] = _Tap(make_llm(c, cd, r, provider=prov, record=a.record), 8 if live else 0)
                return tap["t"]
            _, res, _ = run_case(d, mk, Path(tmp), dry_run=True)
            dirs.append(d)
            truth = _truth(d)
            model = tap["t"].model
            for dt, raw in tap["t"].raw.items():
                for f, v in (raw.get("fields") or {}).items():
                    if v.get("value") is not None and v["value"] != truth.get(dt, {}).get(f):
                        kept = res.extractions[dt].fields[f].value if dt in res.extractions and f in res.extractions[dt].fields else None
                        fixed = " (normalised in code to the truth after verify)" if kept == truth.get(dt, {}).get(f) else ""
                        halluc.append(f"{d.name}/{dt}.{f}: proposed {v['value']!r}, truth {truth.get(dt, {}).get(f)!r}{fixed}")
            for dt, ext in res.extractions.items():
                for f, fld in ext.fields.items():
                    s = stats.setdefault(f, [0, 0])
                    s[1] += 1
                    prop[0] += fld.value is not None or fld.status.value == "UNVERIFIABLE"
                    prop[1] += fld.value is not None and fld.status.value == "VERIFIED"
                    s[0] += fld.status.value == "VERIFIED" and fld.value == truth.get(dt, {}).get(f)
                    if fld.status.value != "VERIFIED" and truth.get(dt, {}).get(f):
                        notes.append(f"{d.name}/{dt}.{f}: {fld.status.value} (truth {truth[dt][f]!r})")
    tot = [sum(s[i] for s in stats.values()) for i in (0, 1)]
    lines = [f"## {SECTIONS[which]}\n\nDate: {date.today()}  \nProvider: {prov}  \nModel: {model}  \n"
             f"Cases (distinct packets): {', '.join(d.name for d in dirs)}  ",
             "full_name is derived in code from the VERIFIED surname + given_names (never asked of the LLM).\n",
             "| field | correct VERIFIED / total | accuracy |\n|---|---|---|"]
    lines += [f"| {f} | {c}/{n} | {c / n:.0%} |" for f, (c, n) in sorted(stats.items())]
    lines += [f"| **all** | {tot[0]}/{tot[1]} | {tot[0] / max(tot[1], 1):.0%} |",
              f"\nHallucinations (non-null proposal differing from truth, before verify): **{len(halluc)}**  \nEvidence pass rate (proposals surviving verify / proposals): {prop[1]}/{prop[0]}\n"]
    lines += [f"- {h}" for h in halluc] + (["\nNot VERIFIED / skipped:\n"] + [f"- {n}" for n in notes] if notes else [])
    if a.live and dirs:  # only a real-provider run (or a replay of its recordings) may write the accuracy file
        lines.insert(1, _quote_rate(dirs))
        _write_section(which, "\n".join(lines) + "\n")
    else:
        lines.insert(0, f"**Provider: {prov}. Not written (pass --live).**\n")
    print("\n".join(lines))
    return 0


def _write_section(which: str, body: str) -> None:
    """EVAL_RESULTS.md holds one section per set; a run replaces only its own section."""
    f = DOCS / "EVAL_RESULTS.md"
    old = f.read_text().split("\n## ")[1:] if f.exists() else []
    parts = {k: next(("## " + x for x in old if x.startswith(t)), "") for k, t in SECTIONS.items()} | {which: body}
    f.write_text("# Eval results\n\nReal model, per-field accuracy against truth.json. Each section is rewritten by "
                 "`eval --live [--record] --set <clean|realistic>` (or from mock_data/replay/ with LLM_PROVIDER=replay).\n\n"
                 + "\n".join(p.rstrip() + "\n" for p in parts.values() if p))


def _check(exp, res) -> list[str]:
    """Return a list of mismatches (empty = pass) for the headline golden fields."""
    bad, got = [], {(i.kind.value, i.field) for i in res.issues}
    bad += [f"missing issue {e['kind']}:{e['field']}" for e in exp["issues"] if (e["kind"], e["field"]) not in got]
    if sorted(res.flags) != sorted(exp["flags"]):
        bad.append(f"flags {res.flags}")
    if res.write_outcome != exp["write_outcome"]:
        bad.append(f"outcome {res.write_outcome}")
    c = exp["crm"]
    if c["action"] != "NO_WRITE" and (res.plan.record_id, res.plan.status, res.plan.field_patch) != (c["target_record"], c["status"], c["field_patch"]):
        bad.append("plan differs")
    if c["action"] == "NO_WRITE" and res.plan.record_id is not None:
        bad.append("unexpected write plan")
    return bad


def test_report(a) -> int:
    rows, fails = [], 0
    with tempfile.TemporaryDirectory() as tmp:
        for name in sorted(p.name for p in CASES.iterdir() if (p / "expected.json").exists()):
            exp, res, _ = run_case(name, lambda c, d, r: make_llm(c, d, r, provider="fake"), Path(tmp))
            bad, c = _check(exp, res), exp["crm"]
            fails += bool(bad)
            e_iss = ", ".join(f"{i['kind']}:{i['field']}" for i in exp["issues"]) or "none"
            g_iss = ", ".join(sorted({f"{i.kind.value}:{i.field}" for i in res.issues})) or "none"
            rows.append(f"| {exp['scenario']} | {name} | {exp['title']} | {exp['write_outcome']} / {c['status'] or c['action']} / {e_iss} "
                        f"| {res.write_outcome} / {res.plan.status or res.plan.reason} / {g_iss} | {'PASS' if not bad else 'FAIL: ' + '; '.join(bad)} |")
    out = (f"# Test results (generated {date.today()}; FakeLLM, frozen clock per case)\n\n"
           "These offline tests prove the control logic (verification, policy, gateway guards, retries) using scripted LLM output. "
           "They do not measure extraction accuracy; that lives in EVAL_RESULTS.md (real model, separate evidence).\n\n"
           f"{len(rows) - fails}/{len(rows)} scenarios match their golden. Issues listed are the expected subset vs everything raised.\n\n"
           "| # | case | scenario | expected (outcome / status / issues) | actual (outcome / status / issues) | result |\n|---|---|---|---|---|---|\n"
           + "\n".join(rows) + "\n")
    (DOCS / "TEST_RESULTS.md").write_text(out)
    print(out)
    return 1 if fails else 0
